export const meta = {
  name: "quick-refactor",
  description: "Quick refactoring workflow: analyze code, suggest improvements, apply changes with verification",
}

export default async function quickRefactor(args, { agent, parallel, readFile, writeFile }) {
  const target = args.target || "."
  const focus = args.focus || "general"

  phase("Analyze code")
  const analysis = await agent(
    `Analyze ${target} for refactoring opportunities. Focus on: ${focus}.
    Return: list of specific refactoring suggestions with file paths and line numbers.
    Prioritize by impact and difficulty.`,
    { agentType: "explore" }
  )

  phase("Plan changes")
  const plan = await agent(
    `Based on this analysis:\n${analysis}\n
    Create a refactoring plan. For each suggestion:
    1. What to change
    2. Why it matters
    3. Risk level (low/medium/high)
    4. Expected outcome`,
    { agentType: "general" }
  )

  phase("Apply low-risk changes")
  const results = await agent(
    `Apply only the LOW RISK refactoring changes from this plan:\n${plan}\n
    Rules:
    - Only apply changes marked as "low risk"
    - Verify each change compiles/passes tests
    - Revert if anything breaks
    - Report what was changed`,
    { agentType: "general" }
  )

  phase("Report")
  const report = `# Refactoring Report

## Analysis
${analysis}

## Changes Applied
${results}

---
Generated by quick-refactor workflow`

  await writeFile("refactor-report.md", report)
  log("Report written to refactor-report.md")

  return report
}
